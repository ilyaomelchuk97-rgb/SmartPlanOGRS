// Тест сборки 22.09-218:
//  В окне «✏ Изменить график» у прошедших дней можно поправить ЧАСЫ:
//   1) клик по прошедшему дню открывает окошко дня (раньше было «не редактируются»);
//   2) «рабочий/выходной» в прошлом не меняется (радио выключены), меняются только часы;
//   3) прошедший выходной/отсутствие не открывается;
//   4) перетаскивание прошедших дней по-прежнему запрещено;
//   5) подсказки в окне обновлены.
const fs = require('fs');
const app = fs.readFileSync('/home/user/root_index/app.js', 'utf8');
let pass = 0, fail = 0;
function ok(cond, name) { if (cond) { pass++; console.log('ok - ' + name); } else { fail++; console.log('FAIL - ' + name); } }
function count(sub) { return app.split(sub).length - 1; }

// 1) прошедшие дни больше не заблокированы (проверяем именно окошко нового окна редактора;
//    в старом недоступном окне 207 страничной ячейки запрет осознанно оставлен)
const _dSl = app.slice(app.indexOf('function openSchEdDayModal'), app.indexOf('function schEdDayClose'));
ok(_dSl.indexOf('не редактируются') === -1, 'в окошке дня окна редактора старый запрет на прошедшие дни удалён');
ok(app.indexOf("var isPast = ds < todayK; // 22.09-218") >= 0, 'флаг isPast в окошке дня');
ok(app.indexOf('S.schEdDay = { uid: uid, ds: ds, past: isPast };') >= 0, 'прошедший день помечается в состоянии окошка');

// 2) ячейки прошедших дней кликабельны, перетаскивание — только будущих
ok(app.indexOf("var act = 'sch-ed-cell';") >= 0 && app.indexOf("var act = (!past) ? 'sch-ed-cell' : '';") === -1, 'клик работает по всем дням (включая прошедшие)');
ok(app.indexOf("var drag = (!past && ci.st !== 'abs');") >= 0, 'перетаскивание по-прежнему только будущих дней');
ok(app.indexOf("(past ? 'opacity:.45;cursor:pointer;' : 'cursor:pointer;')") >= 0, 'курсор-указатель и на прошедших днях');
ok(app.indexOf('⏪ прошедший день: клик — поправить часы') >= 0, 'подсказка на прошедшем рабочем квадратике');

// 3) окошко дня: для прошедшего — только часы
ok(app.indexOf("if (isPast && ci.st !== 'work') { toast('warn', 'В прошедшие дни можно менять только часы рабочего дня'); return; }") >= 0, 'прошедший выходной/отсутствие не открывается');
ok(count("(isPast ? ' disabled' : '')") === 2, 'оба радио «рабочий/выходной» выключаются у прошедшего дня');
ok(count('В прошедшие дни рабочий/выходной не меняется — только часы') === 2, 'пояснение на заблокированных радио (оба)');
ok(app.indexOf('Прошедший день: здесь можно поправить только количество часов (фактическая отработка). ') >= 0, 'подсказка под полем часов для прошедшего дня');
ok(app.indexOf("if (sd.past) st = 'work'; // 22.09-218") >= 0, '«Применить» у прошедшего дня не трогает рабочий/выходной');

// 4) подсказки окна редактора обновлены
ok(app.indexOf('клик по дню — окошко дня (у прошедших — только часы)') >= 0, 'подсказка в шапке окна');
ok(app.indexOf('Прошедшие (отработанные) дни недоступны.') === -1, 'старая подсказка «прошедшие недоступны» удалена');
ok(app.indexOf('Прошедшие дни: клик по рабочему квадратику — окошко, где можно поправить часы') >= 0, 'новая подсказка внизу окна');

console.log('----------------------------------------');
console.log('TEST 218: ' + pass + ' passed, ' + fail + ' failed');
process.exit(fail ? 1 : 0);
